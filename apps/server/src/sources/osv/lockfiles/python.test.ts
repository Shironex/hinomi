const view = (deps: ReturnType<typeof parseLockfile>) =>
  Object.fromEntries(
    deps.map((d) => [
      `${d.name}@${d.version}`,
      `${d.scope} ${d.direct ? 'direct' : 'transitive'} ${d.path?.join('>') ?? ''}`.trim(),
    ]),
  )

describe('normalizePypiName', () => {
  it('lowercases and collapses runs of separators like PEP 503', () => {
    expect(normalizePypiName('Plover_Client')).toBe('plover-client')
    expect(normalizePypiName('zope.interface')).toBe('zope-interface')
    expect(normalizePypiName('A--b__c..D')).toBe('a-b-c-d')
  })
})

describe('toml reader', () => {
  it('reads tables, arrays of tables, inline tables and multi line values', () => {
    const doc = parseToml(`
title = "x" # note
list = [
  1, 2,
  "three",
]
[a.b]
c = { d = 'lit', e = [true] }
[[arr]]
n = 1
[[arr]]
n = """
two"""
`)
    expect(doc).toEqual({
      title: 'x',
      list: [1, 2, 'three'],
      a: { b: { c: { d: 'lit', e: [true] } } },
      arr: [{ n: 1 }, { n: 'two' }],
    })
  })

  it('skips a statement it cannot read and keeps going', () => {
    expect(parseToml('a = \nb = 2\n=\nc = 3\n')).toMatchObject({ b: 2, c: 3 })
  })
})

describe('toml reader prototype safety', () => {
  it('keeps Object.prototype clean for table, dotted key and inline table vectors', () => {
    parseToml('[__proto__]\npolluted = "yes"\n')
    parseToml('__proto__.x = "y"\n')
    parseToml('a = { __proto__ = { z = 1 } }\n[constructor.prototype]\nq = 1\n')
    expect(({} as Record<string, unknown>).polluted).toBeUndefined()
    expect(({} as Record<string, unknown>).x).toBeUndefined()
    expect(({} as Record<string, unknown>).z).toBeUndefined()
    expect(({} as Record<string, unknown>).q).toBeUndefined()
  })

  it('still parses the rest of a file with a poisoned statement', () => {
    const poisoned = `[__proto__]\npolluted = "yes"\n\n${UV_LOCK}`
    expect(parseLockfile(poisoned, 'uv.lock')).toEqual(parseLockfile(UV_LOCK, 'uv.lock'))
    expect(parseToml('# c\n[__proto__]\nk = 1\n')).toEqual({})
    expect(parseToml('a = 1\n__proto__.x = 2\nb = 3\n')).toMatchObject({ a: 1, b: 3 })
  })
})

describe('uv.lock', () => {
  const deps = parseLockfile(UV_LOCK, 'uv.lock')

  it('is registered and returns PyPI dependencies with normalised names', () => {
    expect(hasLockfileParser('apps/api/uv.lock')).toBe(true)
    expect(deps.every((d) => d.ecosystem === 'PyPI')).toBe(true)
  })

  it('tells runtime from dev through the project dependency groups, with paths', () => {
    expect(view(deps)).toEqual({
      'deep-lib@3.3.3': 'dev transitive local-tool>gitdep>deep-lib',
      'pluggy@1.5.0': 'dev transitive pytest>pluggy',
      'plover-client@1.2.0': 'runtime direct plover-client',
      'pytest@8.1.0': 'dev direct pytest',
      'tern-http@2.0.1': 'runtime direct tern-http',
      'wren-metrics@0.4.0': 'runtime direct wren-metrics',
    })
  })

  it('does not report the project itself, path or git packages', () => {
    const names = deps.map((d) => d.name)
    for (const skipped of ['kestrel-api', 'local-tool', 'gitdep']) {
      expect(names).not.toContain(skipped)
    }
  })

  it('names the workspace of the project', () => {
    expect(deps.find((d) => d.name === 'pytest')?.workspaces).toEqual(['kestrel-api'])
  })

  it('keeps both versions of a forked package and picks the one a dependency names', () => {
    const forked = `[[package]]
name = "app"
version = "1.0.0"
source = { virtual = "." }
dependencies = [{ name = "numlib", version = "1.0.0", source = { registry = "https://pypi.org/simple" }, marker = "python_full_version < '3.12'" }, { name = "numlib", version = "2.0.0", marker = "python_full_version >= '3.12'" }]

[[package]]
name = "numlib"
version = "1.0.0"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "numlib"
version = "2.0.0"
source = { registry = "https://pypi.org/simple" }
`
    expect(Object.keys(view(parseLockfile(forked, 'uv.lock')))).toEqual([
      'numlib@1.0.0',
      'numlib@2.0.0',
    ])
  })

  it('has unknown scope without a project and never throws on junk', () => {
    expect(parseLockfile('', 'uv.lock')).toEqual([])
    expect(parseLockfile('[[package]]\nname = \n[weird]\n???', 'uv.lock')).toEqual([])
    const bare = `[[package]]\nname = "lone"\nversion = "1.0"\nsource = { registry = "https://pypi.org/simple" }\n`
    expect(parseLockfile(bare, 'uv.lock')[0]).toMatchObject({ name: 'lone', scope: 'unknown' })
  })
})

describe('poetry.lock', () => {
  it('reads the 1.x layout with category and normalises names', () => {
    const deps = parseLockfile(POETRY_1_CATEGORIES, 'poetry.lock')
    expect(hasLockfileParser('poetry.lock')).toBe(true)
    expect(view(deps)).toEqual({
      'colorama@0.4.6': 'runtime transitive plover-client>colorama',
      'plover-client@1.2.0': 'runtime direct plover-client',
      'pytest@8.1.0': 'dev direct pytest',
      'tern-http@2.0.1': 'runtime transitive plover-client>tern-http',
    })
  })

  it('reads the 2.x layout with groups, main wins over dev', () => {
    expect(view(parseLockfile(POETRY_2, 'poetry.lock'))).toEqual({
      'colorama@0.4.6': 'runtime transitive plover-client>colorama',
      'plover-client@1.2.0': 'runtime direct plover-client',
      'pytest@8.1.0': 'dev direct pytest',
      'tern-http@2.0.1': 'runtime transitive plover-client>tern-http',
    })
  })

  it('skips git sourced packages and tolerates a lock without scope markers', () => {
    const deps = parseLockfile(POETRY_1, 'poetry.lock')
    expect(deps.map((d) => d.name)).not.toContain('internal-lib')
    expect(deps.every((d) => d.scope === 'unknown')).toBe(true)
    expect(parseLockfile('', 'poetry.lock')).toEqual([])
  })
})
