import type { FixCheckResult } from '@hinomi/shared'
import { describe, expect, it } from 'vitest'
import { PLANS, runFor } from '@/fixtures/fix-runs'
import {
  AGENT_OUTCOME_INFO,
  formatCost,
  formatDuration,
  orderedChecks,
  parseStepId,
  previewPlan,
  runNext,
  runnerKindOf,
  runSummary,
  runTimeline,
  runUrgency,
} from './fix-run-meta'

const statuses = (id: number) => runTimeline(runFor(id)!).map((s) => s.status)

describe('runTimeline', () => {
  it('marks the stage a running run is at and leaves the rest to do', () => {
    // Run 44 is running: dispatched, then the workflow run in progress.
    expect(statuses(44)).toEqual(['done', 'now', 'todo', 'todo', 'todo', 'todo', 'todo'])
  })

  it('fails the checks stage and keeps the merge waiting for a person', () => {
    const steps = runTimeline(runFor(41)!)
    expect(steps.map((s) => s.status)).toEqual([
      'done',
      'done',
      'done',
      'fail',
      'todo',
      'todo',
      'todo',
    ])
    expect(steps[3]!.detail).toMatch(/stays a draft/)
    expect(steps[2]!.detail).toBe('#121, draft on hinomi/fix-plan')
  })

  it('fails the dispatch of a run GitHub refused, with the reason', () => {
    const steps = runTimeline(runFor(35)!)
    expect(steps[0]!.status).toBe('fail')
    expect(steps[0]!.detail).toMatch(/404/)
    expect(steps.slice(1).every((s) => s.status === 'todo')).toBe(true)
  })

  it('skips the pull request stages when there was nothing to change', () => {
    expect(statuses(20)).toEqual(['done', 'done', 'skip', 'skip', 'skip', 'skip', 'now'])
  })

  it('fails the merge stage of a closed pull request', () => {
    expect(statuses(38)[4]).toBe('fail')
    expect(runTimeline(runFor(38)!)[4]!.detail).toBe('Closed without merging')
  })

  it('is all done once verified, and fails the rescan when not cleared', () => {
    expect(statuses(12).every((s) => s === 'done')).toBe(true)
    expect(statuses(18).at(-1)).toBe('fail')
  })

  it('skips the deploy stage when no app ships the fix, and fails it when no deploy came', () => {
    expect(statuses(15)).toEqual(['done', 'done', 'done', 'done', 'done', 'skip', 'done'])
    expect(statuses(39)[5]).toBe('fail')
    expect(runTimeline(runFor(39)!)[5]!.detail).toBe('No deploy of the merge commit within 3 days')
    expect(runTimeline(runFor(40)!)[5]!.detail).toBe('ingest-worker shipped it')
    expect(runTimeline(runFor(40)!)[6]!.detail).toBe('The rescan failed 2 times, trying again')
    expect(runTimeline(runFor(18)!)[6]!.detail).toBe('1 of 2 findings cleared')
  })

  it('places a lost or superseded run where it stopped', () => {
    expect(statuses(25)[1]).toBe('fail')
    expect(statuses(31)[3]).toBe('skip')
  })
})

describe('run order and labels', () => {
  it('puts runs that need a person before running and ended ones', () => {
    expect(runUrgency('checks_failing')).toBe(0)
    expect(runUrgency('closed_unmerged')).toBe(0)
    expect(runUrgency('running')).toBe(1)
    expect(runUrgency('verified')).toBe(2)
    expect(runUrgency(undefined)).toBe(2)
  })

  it('names the pull request once there is one', () => {
    expect(runSummary(runFor(41)!)).toBe('PR #121, checks failing')
    expect(runSummary(runFor(44)!)).toBe('Running')
  })
})

describe('orderedChecks', () => {
  const check = (name: string, status: FixCheckResult['status']): FixCheckResult => ({
    name,
    command: `pnpm ${name}`,
    status,
    durationMs: 1,
    output: null,
    truncated: false,
  })

  it('lists failures and timeouts first, otherwise keeps the run order', () => {
    const ordered = orderedChecks([
      check('lint', 'passed'),
      check('test', 'failed'),
      check('build', 'skipped'),
      check('typecheck', 'timeout'),
      check('format', 'passed'),
    ])
    expect(ordered.map((c) => c.name)).toEqual(['test', 'typecheck', 'lint', 'format', 'build'])
  })
})

describe('previewPlan', () => {
  it('sends the safe steps only and shows a diff per file', () => {
    const preview = previewPlan(PLANS[0]!)
    expect(preview.sent.map((s) => s.packageName)).toEqual([
      'tessera',
      'cookie-jar-lite',
      'streamtap',
    ])
    expect(preview.risky.map((s) => s.packageName)).toEqual(['marked-lite'])
    expect(preview.findings).toBe(5)
    expect(preview.files.map((f) => f.path)).toEqual([
      'package.json',
      'apps/web/package.json',
      'pnpm-lock.yaml',
    ])
    const root = preview.files[0]!
    expect(root.lines).toContainEqual({ sign: '+', text: '"tessera": "14.2.9"' })
    expect(root.lines).toContainEqual({ sign: '+', text: '  "streamtap": "0.9.4"' })
    expect(preview.files[2]!.note).toBe('Regenerated by pnpm install')
  })

  it('keeps a safe step the runner cannot apply out of the diff', () => {
    const plan = PLANS[0]!
    const manual = {
      ...plan.steps[0]!,
      id: 'manual:npm:left-pad:1.3.1:none',
      packageName: 'left-pad',
      lockfile: null,
      apply: { type: 'manual' as const },
    }
    const preview = previewPlan({ ...plan, steps: [...plan.steps, manual] })
    expect(preview.notSent.map((s) => s.packageName)).toEqual(['left-pad'])
    expect(preview.files.some((f) => f.lines.some((l) => l.text.includes('left-pad')))).toBe(false)
  })
})

describe('small helpers', () => {
  it('reads the package and target out of a step id', () => {
    expect(parseStepId('manifest_bump:npm:tessera:14.2.9:pnpm-lock.yaml')).toEqual({
      packageName: 'tessera',
      to: '14.2.9',
    })
    expect(parseStepId('broken')).toBeNull()
  })

  it('formats durations', () => {
    expect(formatDuration(420)).toBe('420 ms')
    expect(formatDuration(4_200)).toBe('4.2 s')
    expect(formatDuration(64_200)).toBe('1 min 4 s')
    expect(formatDuration(120_000)).toBe('2 min')
  })
})

describe('majors runs', () => {
  it('lists the major upgrades of a plan apart from the safe steps', () => {
    const marked = PLANS.find((p) => p.repo.id === 18)!
    const preview = previewPlan(marked)
    expect(preview.sent.map((s) => s.packageName)).toEqual(['streamtap'])
    expect(preview.majors.map((s) => s.packageName)).toEqual(['marked-lite', 'argkit'])
    // The agent is off for a plan with no major upgrade the runner can take.
    expect(previewPlan(PLANS.find((p) => p.repo.id === 2)!).majors).toEqual([])
    expect(previewPlan(PLANS.find((p) => p.repo.id === 16)!).sent).toEqual([])
  })

  it('words what happens next for a majors run, and keeps the fix wording otherwise', () => {
    expect(runNext({ kind: 'majors', state: 'running' })).toMatch(/coding agent/)
    expect(runNext({ kind: 'majors', state: 'checks_passing' })).toMatch(/draft pull request/)
    expect(runNext({ kind: 'fix', state: 'running' })).toMatch(/safe steps/)
    // A state with no majors wording falls back to the shared one.
    expect(runNext({ kind: 'majors', state: 'merged' })).toMatch(/deploy of the merge commit/)
  })

  it('describes the workflow run stage by the agent, not the safe steps', () => {
    expect(runTimeline(runFor(50)!)[1]!.detail).toBe(
      'The agent is editing the code for the major upgrades',
    )
    expect(runTimeline(runFor(51)!)[1]!.detail).toBe('Agent: changed the code, 37 turns, $3.42')
    const failed = runTimeline(runFor(53)!)
    expect(failed.map((s) => s.status)).toEqual([
      'done',
      'fail',
      'todo',
      'todo',
      'todo',
      'todo',
      'todo',
    ])
    expect(failed[1]!.detail).toMatch(/The agent timed out/)
  })

  it('names every agent outcome and formats the cost', () => {
    expect(Object.keys(AGENT_OUTCOME_INFO)).toEqual([
      'changed',
      'no_changes',
      'failed',
      'timeout',
      'refused',
    ])
    expect(formatCost(3.4)).toBe('$3.40')
    expect(formatCost(0)).toBe('$0.00')
  })
})

describe('runs on other runners', () => {
  it('names the runner kind, with GitHub Actions when an older server sends none', () => {
    expect(runnerKindOf(undefined)).toBe('github_actions')
    expect(runnerKindOf({ settings: { enabled: true, workflow: 'hinomi-fix.yml' } })).toBe(
      'github_actions',
    )
    expect(
      runnerKindOf({ settings: { enabled: true, workflow: 'hinomi-fix.yml', kind: 'local' } }),
    ).toBe('local')
  })

  it('words what happens next without GitHub for a webhook or local run', () => {
    expect(runNext(runFor(60)!)).toBe(
      'The webhook runner applies the safe steps. Waiting for its result.',
    )
    expect(runNext(runFor(61)!)).toBe('The local runner applies the safe steps on this host.')
    // From the push on the wording is shared.
    expect(runNext(runFor(64)!)).toBe(runNext({ ...runFor(64)!, runner: 'github_actions' }))
    expect(runNext(runFor(44)!)).toMatch(/runner applies the safe steps/)
  })

  it('titles the runner stage after the runner and drops the GitHub wording', () => {
    const webhook = runTimeline(runFor(60)!)
    expect(webhook[0]!.detail).toBe('The webhook runner accepted the plan')
    expect(webhook[1]!.title).toBe('Webhook runner')
    const local = runTimeline(runFor(61)!)
    expect(local[1]!.title).toBe('Local runner')
    expect(runTimeline(runFor(44)!)[1]!.title).toBe('Workflow run')
  })

  it('fails the dispatch with the reason the runner gave', () => {
    const run = {
      ...runFor(62)!,
      state: 'failed' as const,
      at: { ...runFor(62)!.at, dispatched: null },
    }
    const steps = runTimeline(run)
    expect(steps[0]!.status).toBe('fail')
    expect(steps[0]!.detail).toBe(run.stateReason)
  })
})
